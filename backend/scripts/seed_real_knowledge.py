def seed_space(code, docs):
    space = KnowledgeSpace.objects.filter(code=code).first()
    if space is None:
        print(f"[MISS] space {code} not found — skipped")
        return
    print(f"\n=== {space.name} ({code}) ===")
    from apps.rag.pipeline import RAGPipeline

    pipeline = RAGPipeline(ingestion=True)
    for title, body in docs:
        doc = Document.objects.filter(space=space, title=title).first()
        created = doc is None
        if created:
            doc = Document.objects.create(
                space=space, title=title, text_content=body,
                file_type="md", file_size=0, uploaded_by=admin, status="draft",
            )
        elif doc.text_content != body:
            doc.text_content = body
            doc.save(update_fields=["text_content"])
        if not created and doc.chunk_count and doc.status == "active":
            print(f"  = {title} (already ingested)")
            continue
        try:
            chunks = pipeline.ingest_text_content(doc)
            doc.chunk_count = len(chunks)
        except Exception as exc:
            print(f"  ! embed failed for {title}: {exc} — activating without chunks")
        doc.status = "active"
        doc.save(update_fields=["chunk_count", "status"])
        print(f"  + {title} ({doc.chunk_count} chunks)")

    # Re-sync wikilinks for EVERY active doc in the space (new + pre-existing)
    # so all edges resolve now that every target title exists.
    total_links = 0
    for doc in Document.objects.filter(space=space, status__in=["active", "stale"]):
        total_links += sync_document_links(doc)
